import json
import os

# Absolute path definitions
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
EXAMS_DIR = os.path.join(BASE_DIR, "exams")

# Validation parameters
VALID_CHARS = set("ABCÇDEFGĞHIİJKLMNOÖPRSŞTUÜVYZ")

def validate_word(word):
    if not (2 <= len(word) <= 15):
        raise ValueError(f"Word '{word}' (length {len(word)}) is not between 2 and 15 letters.")
    for char in word:
        if char not in VALID_CHARS:
            raise ValueError(f"Word '{word}' contains invalid character '{char}'. Only uppercase Turkish letters are allowed.")

def build_exam_file(filename, subject_name, units):
    # Verify each unit has exactly 50 words and words are valid
    for unit in units:
        words = unit["words"]
        if len(words) != 50:
            raise ValueError(f"Unit '{unit['name']}' in {filename} has {len(words)} words instead of 50.")
        
        seen_words = set()
        for item in words:
            word = item["word"]
            validate_word(word)
            if word in seen_words:
                raise ValueError(f"Duplicate word '{word}' found in unit '{unit['name']}' of {filename}.")
            seen_words.add(word)

    # Save to file
    os.makedirs(EXAMS_DIR, exist_ok=True)
    filepath = os.path.join(EXAMS_DIR, filename)
    data = {
        "subject": subject_name,
        "units": units
    }
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Successfully generated: {filepath}")

